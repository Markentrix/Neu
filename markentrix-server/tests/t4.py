import httpx
c=httpx.Client(base_url="http://localhost:8000",headers={"X-MK":"1"},timeout=20)
def ok(n,r,code=200):
    print(("OK   " if r.status_code==code else "FAIL ")+n, "" if r.status_code==code else (r.status_code,r.text[:200]))
    return r
ok("login",c.post("/api/login",json={"email":"chef@test.de","password":open("/var/tmp/pt/adminpw").read().strip()}))
